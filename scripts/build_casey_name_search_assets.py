"""Embed the approved, lossless Casey assets; no runtime image requests."""
from pathlib import Path
import base64,hashlib,json
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'assets/casey-name-search'
manifest=json.loads((ASSETS/'manifest.json').read_text())
result={k:manifest[k]for k in['frameWidth','frameHeight','frameCount','frameDurationMs','groundPeriodMs','groundY','groundHeight','order']}
for key,name in [('sprite','sprite.png'),('idle','placeholder.png'),('ground','ground.png')]:
 data=(ASSETS/name).read_bytes()
 assert hashlib.sha256(data).hexdigest()==manifest['sha256'][name],name
 result[key]='data:image/png;base64,'+base64.b64encode(data).decode()
output=ROOT/'src/tampermonkey/17a-name-search-casey-assets.js'
output.write_text('// Generated by scripts/build_casey_name_search_assets.py. Exact approved RGBA artwork.\nconst CASEY_NAME_SEARCH_ASSETS = Object.freeze('+json.dumps(result,separators=(',',':'))+');\n')
print('Wrote',output.relative_to(ROOT))
